"""Bundle the tested Studio source with its checked file installer. No HTTP or process launch."""
from pathlib import Path
root=Path(__file__).resolve().parents[1]
s=(root/'Composition Studio.lua').read_text()
# Reuse validation, backup and rename rollback from the production installer.
a=s.index('local function complete_update(status,fresh)')
b=s.index(' update_status="Update auf "..rv.." installiert. Neustart …"',a)
install=s[a:b]+''' update_status="Version "..rv.." wurde installiert. Bitte Composition Studio erneut öffnen."
 busy=false
 reaper.SetExtState(EXT_SECTION,WINDOW_STATE_KEY,"0",true)
end
'''
a=s.index('local function read_file(p)');b=s.index('local update_job=nil',a)
files_and_versions=s[a:b]
header='''-- @description Composition Studio: Offline-Installation zur Wiederherstellung
-- @version 1.0.0
-- Generated by tools/build_offline_installer.py; contains the complete Studio script.
local SCRIPT_NAME="Composition Studio"
local EXT_SECTION="CompositionStudio"
local WINDOW_STATE_KEY="WindowOpen"
local SCRIPT_PATH=reaper.GetExtState(EXT_SECTION,"ActiveScriptPath")
local VERSION="0.0.0"
local busy=false
local update_status=""
local function message(s)reaper.ShowMessageBox(s,SCRIPT_NAME.." – Offline-Installation",0)end
'''
assert ']====]' not in s
payload='local fresh=[====[\n'+s+']====]\n'
footer='''
local previous=SCRIPT_PATH~="" and read_file(SCRIPT_PATH) or nil
if not previous or not previous:find('local SCRIPT_NAME="Composition Studio"',1,true) then
 message("Die registrierte Studio-Datei wurde nicht gefunden. Bitte Composition Studio einmal starten und wieder schließen.");return
end
VERSION=previous:match("%-%- @version%s+([%w%.%-]+)") or "0.0.0"
local ok,err=pcall(complete_update,"200",fresh)
if not ok then message("Installation abgebrochen: "..tostring(err));return end
message(update_status)
'''
(root/'Composition-Studio-Offline-Install.lua').write_text(header+files_and_versions+payload+install+footer)
print('Built offline installer with complete tested Studio source')
