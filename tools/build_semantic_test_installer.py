"""Build an isolated, analysis-only REAPER test from the current production source.
No stable file, autostart, settings, or updater is replaced.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def candidate_source():
    source = (ROOT / 'Composition Studio.lua').read_text()
    def replace_once(old, new):
        nonlocal source
        assert source.count(old) == 1, old
        source = source.replace(old, new, 1)
    replace_once('\nlocal SCRIPT_NAME="Composition Studio"',
                 '\nlocal SCRIPT_NAME="Composition Studio – Semantik-Test"')
    replace_once('ensure_native_startup_hook()\nif type(reaper.ImGui_CreateContext)',
                 '-- No autostart installation in the isolated test.\nif type(reaper.ImGui_CreateContext)')
    replace_once('reaper.SetExtState(EXT_SECTION,"ActiveScriptPath",SCRIPT_PATH,true)',
                 '-- Stable ActiveScriptPath remains untouched.')
    for marker in ('local function install_update()', 'function workflow_adapter.apply()',
                   'function workflow_adapter.review(task)'):
        replace_once(marker, marker + '\n if true then update_status="Semantik-Test: nur Analyse, keine Anwendung oder Updates.";busy=false;return end')
    replace_once('local function begin_process(request)', '''local function begin_process(request)
 if not (request:lower():find("analys",1,true) or request:lower():find("untersuch",1,true)) then
  add("KI","Semantik-Test: Bitte nur eine musikalische Notationsanalyse anfordern.");busy=false;return
 end''')
    replace_once('"Studio v"..VERSION', '"Semantik-Test · Basis "..VERSION')
    source = source.replace('CompositionStudio', 'CompositionStudioSemanticTest')
    source = source.replace('Composition-Studio-Last-Diagnosis.json', 'Composition-Studio-Semantic-Test-Last-Diagnosis.json')
    # Reads can reuse existing provider/key/font preferences. All writes use the test namespace.
    prelude = '''-- Isolated settings reader. Never copies or writes stable settings.
local native_reaper=reaper
local reaper=setmetatable({GetExtState=function(section,key)
 local value=native_reaper.GetExtState(section,key)
 if value=="" and section=="CompositionStudioSemanticTest" and key~="WindowOpen" and key~="ActiveScriptPath" then
  return native_reaper.GetExtState("CompositionStudio",key)
 end
 return value
end},{__index=native_reaper})
'''
    return prelude + source

def build():
    payload = candidate_source()
    assert ']====]' not in payload
    installer = '''-- @description Composition Studio: isolierten Semantik-Test installieren und starten
-- @version 1.0.0
-- Generated by tools/build_semantic_test_installer.py. Not a stable release.
local payload=[====[
''' + payload + ''']====]
local function install()
 assert(load(payload,"semantic-test","t"),"Lua-Syntaxprüfung fehlgeschlagen")
 local dir=reaper.GetResourcePath().."/Scripts/CompositionStudioSemanticTest"
 reaper.RecursiveCreateDirectory(dir,0)
 local path=dir.."/Composition Studio Semantic Test.lua"
 local pending=path..".pending"
 local f=assert(io.open(pending,"wb"),"Testdatei kann nicht geschrieben werden")
 assert(f:write(payload));assert(f:close())
 local check=assert(io.open(pending,"rb"));local actual=check:read("*a");check:close()
 assert(actual==payload,"Testdatei ist unvollständig")
 local old=io.open(path,"rb")
 if old then
  old:close();os.remove(path..".backup");assert(os.rename(path,path..".backup"))
 end
 local ok,why=os.rename(pending,path)
 if not ok then os.rename(path..".backup",path);error(why)end
 assert(reaper.AddRemoveReaScript(true,0,path,true)~=0,"Registrierung der Testaktion fehlgeschlagen")
 dofile(path)
end
local ok,err=pcall(install)
if not ok then reaper.ShowMessageBox(tostring(err),"Composition Studio – Semantik-Test",0)end
'''
    path = ROOT / 'Composition-Studio-Semantic-Test-Install.lua'
    path.write_text(installer, encoding='utf-8', newline='\n')
    print('Built isolated semantic test installer:', path.name)

if __name__ == '__main__':
    build()
